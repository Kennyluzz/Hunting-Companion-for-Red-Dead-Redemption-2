#!/usr/bin/env python3
"""Generate src/embedded_hunting_recommendations.hpp.

The table holds the game's own clean-kill advice by Animal Compendium
short-description label (data/compendium_advice.json, built from the game's
English string table by tools/build_compendium_advice.py), with the HUD icon
for each weapon and ammunition (data/weapon_icons.json). The mod asks the game
for the focused animal's label and looks it up here.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS_PATH = ROOT / "data" / "weapon_icons.json"
ADVICE_PATH = ROOT / "data" / "compendium_advice.json"
OUTPUT_PATH = ROOT / "src" / "embedded_hunting_recommendations.hpp"


def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def main() -> None:
    icons = json.loads(ICONS_PATH.read_text(encoding="utf-8"))
    weapons = icons["weaponTextures"]
    ammo = icons["ammoTextures"]
    labels = json.loads(ADVICE_PATH.read_text(encoding="utf-8"))["labels"]

    lines = [
        "#pragma once",
        "// Generated by tools/embed_hunting_recommendations.py. Do not edit.",
        "// The game's own Animal Compendium clean-kill advice, by short-description label.",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace hunting_companion::hunting {",
        "struct AmmoIcon { const char* label; const char* texture; };",
        "struct WeaponChoice { const char* label; const char* texture; const AmmoIcon* ammo; std::size_t ammoCount; };",
        "struct Recommendation { const WeaponChoice* choices; std::size_t choiceCount; };",
    ]
    # Many labels share the same advice; each distinct advice is emitted once.
    shared: dict[str, str] = {}
    rows: list[tuple[int, str]] = []
    for row in labels:
        key = json.dumps(row["choices"], sort_keys=True)
        if key not in shared:
            symbol = f"kAdvice{len(shared)}"
            entries = []
            for index, choice in enumerate(row["choices"]):
                weapon = choice["weapon"]
                if weapon not in weapons:
                    raise SystemExit(f'{row["id"]}: no icon for weapon "{weapon}"')
                ammo_names = choice.get("ammo", [])
                ammo_symbol = f"{symbol}Ammo{index}"
                if ammo_names:
                    for name in ammo_names:
                        if name not in ammo:
                            raise SystemExit(f'{row["id"]}: no icon for ammunition "{name}"')
                    lines.append(f"inline constexpr AmmoIcon {ammo_symbol}[] = {{")
                    lines.extend(f"    {{{cpp_string(n)}, {cpp_string(ammo[n])}}}," for n in ammo_names)
                    lines.append("};")
                    entries.append(f"    {{{cpp_string(weapon)}, {cpp_string(weapons[weapon])}, {ammo_symbol}, "
                                   f"sizeof({ammo_symbol}) / sizeof({ammo_symbol}[0])}},")
                else:
                    entries.append(f"    {{{cpp_string(weapon)}, {cpp_string(weapons[weapon])}, nullptr, 0}},")
            lines.append(f"inline constexpr WeaponChoice {symbol}[] = {{")
            lines.extend(entries)
            lines.append("};")
            shared[key] = symbol
        rows.append((int(row["id"], 16), shared[key]))
    rows.sort()
    if not rows or len({label for label, _ in rows}) != len(rows):
        raise SystemExit("The Compendium advice table is empty or has duplicate labels")
    lines.append("struct LabelAdvice { std::uint32_t label; Recommendation advice; };")
    lines.append("inline constexpr LabelAdvice kLabelAdvice[] = {  // sorted by label")
    for label, symbol in rows:
        lines.append(f"    {{0x{label:08X}u, {{{symbol}, sizeof({symbol}) / sizeof({symbol}[0])}}}},")
    lines += [
        "};",
        "inline constexpr std::size_t kLabelAdviceCount = sizeof(kLabelAdvice) / sizeof(kLabelAdvice[0]);",
        "// The advice for a Compendium short-description label, or nullptr if unknown.",
        "inline const Recommendation* find_by_label(std::uint32_t label) noexcept {",
        "    std::size_t low = 0, high = kLabelAdviceCount;",
        "    while (low < high) {",
        "        const std::size_t mid = (low + high) / 2;",
        "        if (kLabelAdvice[mid].label < label) low = mid + 1;",
        "        else high = mid;",
        "    }",
        "    return (low < kLabelAdviceCount && kLabelAdvice[low].label == label) ? &kLabelAdvice[low].advice : nullptr;",
        "}",
        "} // namespace hunting_companion::hunting",
        "",
    ]
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUTPUT_PATH}: {len(rows)} Compendium labels, {len(shared)} distinct pieces of advice.")


if __name__ == "__main__":
    main()
