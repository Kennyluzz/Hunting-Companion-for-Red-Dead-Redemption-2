#!/usr/bin/env python3
"""Generate the embedded hunting recommendation table from its audited JSON source."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "hunting_recommendations.json"
OUTPUT_PATH = ROOT / "src" / "embedded_hunting_recommendations.hpp"

def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)

def identifier(value: str) -> str:
    result = re.sub(r"[^A-Za-z0-9_]", "_", value)
    if not result or result[0].isdigit():
        result = "_" + result
    return result

def main() -> None:
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    if data.get("schemaVersion") != 1:
        raise SystemExit("Unsupported hunting recommendation schema")
    recommendations = data.get("recommendations", [])
    species = [row["species"] for row in recommendations]
    if len(species) != len(set(species)):
        raise SystemExit("Duplicate model species in recommendation data")

    weapons = data["weaponTextures"]
    ammo = data["ammoTextures"]
    lines = [
        "#pragma once",
        "// Generated by tools/embed_hunting_recommendations.py.",
        "#include <cstddef>",
        "#include <cstring>",
        "namespace hunting_companion::hunting {",
        "struct AmmoIcon { const char* label; const char* texture; };",
        "struct WeaponChoice { const char* label; const char* texture; const AmmoIcon* ammo; std::size_t ammoCount; };",
        "struct Recommendation { const char* species; const WeaponChoice* choices; std::size_t choiceCount; };",
    ]
    choice_symbols = []
    for row in recommendations:
        symbol = identifier(row["species"])
        row_choices = []
        for index, choice in enumerate(row["choices"]):
            weapon = choice["weapon"]
            if weapon not in weapons:
                raise SystemExit(f'{row["species"]}: unknown weapon "{weapon}"')
            ammo_names = choice.get("ammo", [])
            for ammo_name in ammo_names:
                if ammo_name not in ammo:
                    raise SystemExit(f'{row["species"]}: unknown ammo "{ammo_name}"')
            ammo_symbol = f"kAmmo_{symbol}_{index}"
            if ammo_names:
                lines.append(f"inline constexpr AmmoIcon {ammo_symbol}[] = {{")
                for ammo_name in ammo_names:
                    lines.append(f"    {{{cpp_string(ammo_name)}, {cpp_string(ammo[ammo_name])}}},")
                lines.append("};")
                ammo_expr = ammo_symbol
                ammo_count = f"sizeof({ammo_symbol}) / sizeof({ammo_symbol}[0])"
            else:
                ammo_expr = "nullptr"
                ammo_count = "0"
            row_choices.append(
                f"    {{{cpp_string(weapon)}, {cpp_string(weapons[weapon])}, {ammo_expr}, {ammo_count}}},"
            )
        choice_symbol = f"kChoices_{symbol}"
        lines.append(f"inline constexpr WeaponChoice {choice_symbol}[] = {{")
        lines.extend(row_choices)
        lines.append("};")
        choice_symbols.append((row["species"], choice_symbol))
    lines.append("inline constexpr Recommendation kRecommendations[] = {")
    for species_name, choice_symbol in choice_symbols:
        lines.append(
            f"    {{{cpp_string(species_name)}, {choice_symbol}, sizeof({choice_symbol}) / sizeof({choice_symbol}[0])}},"
        )
    lines += [
        "};",
        "inline const Recommendation* find(const char* species) noexcept {",
        "    if (species == nullptr) return nullptr;",
        "    for (const auto& entry : kRecommendations) {",
        "        if (std::strcmp(entry.species, species) == 0) return &entry;",
        "    }",
        "    return nullptr;",
        "}",
        "} // namespace hunting_companion::hunting",
        "",
    ]
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUTPUT_PATH} for {len(recommendations)} runtime species.")

if __name__ == "__main__":
    main()
