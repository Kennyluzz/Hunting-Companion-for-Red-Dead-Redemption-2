#!/usr/bin/env python3
"""Generate src/embedded_ini_template.hpp from HuntingCompanion.ini.

The shipped ini is the template the mod uses to rewrite an older ini in the
current layout, keeping the player's values (src/ini_upgrade.cpp).
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "HuntingCompanion.ini"
OUTPUT = ROOT / "src" / "embedded_ini_template.hpp"


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    match = re.search(r"^IniVersion=(\d+)$", text, re.M)
    if match is None:
        raise SystemExit("HuntingCompanion.ini has no IniVersion line")
    if ")HCINI\"" in text:
        raise SystemExit("HuntingCompanion.ini contains the raw-string delimiter")
    OUTPUT.write_text(
        "#pragma once\n"
        "// Generated by tools/embed_ini.py from HuntingCompanion.ini. Do not edit.\n"
        "namespace hunting_companion::ini {\n"
        f"inline constexpr int kIniVersion = {match.group(1)};\n"
        f"inline constexpr char kTemplate[] = R\"HCINI({text})HCINI\";\n"
        "}  // namespace hunting_companion::ini\n",
        encoding="utf-8")
    print(f"Wrote {OUTPUT} (IniVersion {match.group(1)})")


if __name__ == "__main__":
    main()
