#!/usr/bin/env python3
"""Generate src/embedded_satchel_carcasses.hpp from the game's own English text.

Small animals go into the satchel as carcass items ("Perfect Squirrel Carcass").
Their inventory item IDs follow the game's naming
PROVISION_ANIMAL_CARCASS_<ANIMAL>_<POOR|HIGH_QUALITY|PERFECT>, and the game's
string table labels each one with that same ID. This tool keeps only the IDs the
string table actually has, so every entry is a real game item, and writes which
species and quality each one is. Crafting Uses then counts a satchel carcass for
what it gives (pelt, feathers) the way it counts a carried animal.

    python tools/build_satchel_carcasses.py "RDR2 Official Language - English 1.0.zip"
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_compendium_advice import read_strings  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "embedded_satchel_carcasses.hpp"

# The mod's species names (as in its material table) and the animal names the
# game uses in carcass item IDs.
SPECIES_TOKENS = {
    "Alligator": ["ALLIGATOR"], "Armadillo": ["ARMADILLO"], "Badger": ["BADGER"],
    "Beaver": ["BEAVER"], "Blue Jay": ["BLUEJAY"], "Buck": ["BUCK"],
    "California Condor": ["CALICONDOR"], "Canada Goose": ["GOOSE"],
    "Cardinal": ["CARDINAL"], "Cedar Waxwing": ["CEDARWAXWING"], "Chicken": ["CHICKEN"],
    "Cougar": ["COUGAR"], "Coyote": ["COYOTE"], "Crow": ["CROW"], "Deer": ["DEER"],
    "Duck": ["DUCK"], "Eagle": ["EAGLE"], "Fox": ["FOX"], "Gila Monster": ["GILA"],
    "Goat": ["GOAT"], "Hawk": ["HAWK"], "Iguana": ["IGUANA"], "Loon": ["LOON"],
    "Muskrat": ["MUSKRAT"], "Opossum": ["OPOSSUM"], "Oriole": ["ORIOLE"], "Owl": ["OWL"],
    "Panther": ["PANTHER"], "Pheasant": ["PHEASANT"], "Pig": ["PIG"], "Pigeon": ["PIGEON"],
    "Pronghorn": ["PRONGHORN"], "Quail": ["QUAIL"], "Rabbit": ["RABBIT"],
    "Raccoon": ["RACOON", "RACCOON"], "Ram": ["RAM"], "Rat": ["RAT"],
    "Rattlesnake": ["SNAKE"], "Raven": ["RAVEN"], "Robin": ["ROBIN"],
    "Rooster": ["ROOSTER"], "Seagull": ["SEAGULL"], "Sheep": ["SHEEP"], "Skunk": ["SKUNK"],
    "Songbird": ["SONGBIRD"], "Sparrow": ["SPARROW"], "Squirrel": ["SQUIRREL"],
    "Turkey": ["TURKEY"], "Vulture": ["VULTURE"], "Wolf": ["WOLF"],
    "Woodpecker": ["WOODPECKER"],
}
QUALITIES = (("POOR", 0), ("HIGH_QUALITY", 1), ("PERFECT", 2))


def joaat(text: str) -> int:
    value = 0
    for byte in text.lower().encode():
        value = (value + byte) & 0xFFFFFFFF
        value = (value + (value << 10)) & 0xFFFFFFFF
        value ^= value >> 6
    value = (value + (value << 3)) & 0xFFFFFFFF
    value ^= value >> 11
    return (value + (value << 15)) & 0xFFFFFFFF


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("english", type=Path, help="English text export (.zip or .xml)")
    args = parser.parse_args()
    strings = read_strings(args.english)

    rows = []
    for species, tokens in sorted(SPECIES_TOKENS.items()):
        for token in tokens:
            for suffix, quality in QUALITIES:
                item = f"PROVISION_ANIMAL_CARCASS_{token}_{suffix}"
                label = strings.get(joaat(item))
                if label is not None and label.endswith("Carcass"):
                    rows.append((joaat(item), species, quality, item, label))
    if not rows:
        raise SystemExit("No satchel carcass items found; is this the English text export?")
    found = {species for _, species, *_ in rows}
    missing = sorted(set(SPECIES_TOKENS) - found)

    lines = [
        "#pragma once",
        "// Generated by tools/build_satchel_carcasses.py. Do not edit.",
        "// Satchel carcass items (the game's PROVISION_ANIMAL_CARCASS_* IDs), by species and quality.",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace hunting_companion::satchel {",
        "struct CarcassItem { std::uint32_t item; const char* species; int quality; };  // 0 poor, 1 good, 2 perfect",
        "inline constexpr CarcassItem kCarcassItems[] = {",
    ]
    for item_hash, species, quality, item, label in rows:
        lines.append(f'    {{0x{item_hash:08X}u, "{species}", {quality}}},  // {item}: {label}')
    lines += [
        "};",
        "inline constexpr std::size_t kCarcassItemCount = sizeof(kCarcassItems) / sizeof(kCarcassItems[0]);",
        "}  // namespace hunting_companion::satchel",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}: {len(rows)} carcass items for {len(found)} species.")
    if missing:
        print("No satchel carcass item for: " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
