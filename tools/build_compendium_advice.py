#!/usr/bin/env python3
"""Build data/compendium_advice.json from the game's own English text.

The game's Animal Compendium gives every animal a short description ending in a
clean-kill line, for example "Use a Bow with Small Game Arrows for a clean kill."
At run time the mod asks the game for the focused animal's short-description label
(COMPENDIUM_GET_SHORT_DESCRIPTION_FROM_PED) and looks the label up in this table,
so the weapon and ammunition icons always match the game's own advice, whatever
language the game runs in.

Input: the English export of the game's text, as an "RDR2 Official Language -
English ... .zip" (one XML inside) or the XML itself, with entries of the form
<String id="0x1234ABCD">text</String>.

    python tools/build_compendium_advice.py "RDR2 Official Language - English 1.0.zip"

Any clean-kill wording the phrase table below does not know stops the build, so
nothing is guessed; add the wording to PARTS and rerun.
"""
from __future__ import annotations

import argparse
import json
import re
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "data" / "compendium_advice.json"

CLEAN_KILL = re.compile(r"\bUse (?:a |an )?(.+?) for a clean kill\.", re.IGNORECASE)

# One part of the advice (the text between "or"s) -> weapon and ammunition.
PARTS = [
    (r"(?:a |an )?bow with (?:a |an )?small game arrows?", ("Bow", ["Small Game Arrows"])),
    (r"(?:a |an )?bow with (?:a |an )?improved arrows?", ("Bow", ["Improved Arrows"])),
    (r"(?:a |an )?bow with (?:a |an )?poison(?:ed)? arrows?", ("Bow", ["Poisoned Arrows"])),
    (r"(?:a |an )?bow(?: with (?:a |an )?arrows?)?", ("Bow", [])),
    (r"(?:a |an )?varmint rifle", ("Varmint Rifle", [])),
    (r"(?:a |an )?repeater", ("Repeater", [])),
    (r"(?:a |an )?long[- ]scope(?:d)? rifle", ("Sniper rifle", [])),
    (r"(?:a |an )?rifle", ("Rifle", [])),
]


def read_strings(path: Path) -> dict[int, str]:
    def parse(stream) -> dict[int, str]:
        out: dict[int, str] = {}
        for _, element in ET.iterparse(stream, events=("end",)):
            if element.tag.lower() == "string":
                raw_id = element.attrib.get("id", "")
                if raw_id.lower().startswith("0x"):
                    value = "".join(element.itertext()).strip()
                    if value:
                        out[int(raw_id, 16)] = value
                element.clear()
        return out

    if path.suffix.lower() == ".zip":
        with zipfile.ZipFile(path) as archive:
            names = [n for n in archive.namelist() if n.lower().endswith(".xml")]
            if len(names) != 1:
                raise SystemExit(f"{path.name}: expected one XML inside, found {len(names)}")
            with archive.open(names[0]) as stream:
                return parse(stream)
    with path.open("rb") as stream:
        return parse(stream)


def choices_for(advice: str) -> list[dict] | None:
    choices = []
    for part in re.split(r"\s+or\s+", advice.strip(), flags=re.IGNORECASE):
        for pattern, (weapon, ammo) in PARTS:
            if re.fullmatch(pattern, part.strip(), flags=re.IGNORECASE):
                choices.append({"weapon": weapon, "ammo": list(ammo)})
                break
        else:
            return None
    return choices


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("english", type=Path, help="English text export (.zip or .xml)")
    args = parser.parse_args()

    strings = read_strings(args.english)
    labels = []
    unknown = []
    for label_id, text in sorted(strings.items()):
        match = CLEAN_KILL.search(text)
        if not match:
            continue
        choices = choices_for(match.group(1))
        if choices is None:
            unknown.append(f"0x{label_id:08X}: {match.group(0)}")
            continue
        labels.append({"id": f"0x{label_id:08X}", "advice": match.group(0), "choices": choices})
    if unknown:
        raise SystemExit("Clean-kill wording not in the phrase table:\n  " + "\n  ".join(unknown))
    if not labels:
        raise SystemExit("No clean-kill lines found; is this the English text export?")

    OUTPUT.write_text(json.dumps({
        "description": ("Clean-kill advice from the game's own Animal Compendium text, by the "
                        "short-description label the game returns for an animal "
                        "(COMPENDIUM_GET_SHORT_DESCRIPTION_FROM_PED). Generated by "
                        "tools/build_compendium_advice.py from the game's English text."),
        "labels": labels,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT} with {len(labels)} clean-kill labels.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
