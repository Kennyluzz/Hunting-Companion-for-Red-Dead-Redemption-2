#!/usr/bin/env python3
"""Generate src/embedded_languages.hpp from HuntingCompanion-Languages/*.lang."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = root / "HuntingCompanion-Languages"
out = root / "src" / "embedded_languages.hpp"
files = sorted(source.glob("*.lang"))
if not files:
    raise SystemExit("No .lang files found")
lines = ["#pragma once", "// Generated by tools/embed_languages.py.",
         "namespace hunting_companion::embedded {",
         "struct LocaleBlob { const char* locale; const char* contents; };"]
for index, path in enumerate(files):
    locale = path.stem
    delimiter = f"HCL{index}"
    content = path.read_text(encoding="utf-8")
    if f"){delimiter}\"" in content:
        raise SystemExit(f"Raw-string delimiter collision in {path}")
    symbol = "kLocale_" + locale.replace("-", "_")
    lines.append(f'inline constexpr char {symbol}[] = R"{delimiter}({content}){delimiter}";')
lines.append("inline constexpr LocaleBlob kLocales[] = {")
for path in files:
    symbol = "kLocale_" + path.stem.replace("-", "_")
    lines.append(f'    {{"{path.stem}", {symbol}}},')
lines += ["};", "} // namespace hunting_companion::embedded", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {out}")
